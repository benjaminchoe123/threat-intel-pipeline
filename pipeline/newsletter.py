"""Signal & Noise: a published weekly report, formatted as a newsletter issue.

Two outputs, both pure text transformations — no network, no Claude calls — and
both accept only reports that already went through the gated pipeline.publish:

- GitHub Pages (the home of the newsletter): one Jekyll post per issue in
  docs/_posts/, listed at /newsletter and syndicated at /feed.xml. Written
  automatically by pipeline.publish, in the same commit as the report.
- Substack copy: python -m pipeline.newsletter 2026-W29, for pasting by hand.
  Substack has no posting API.

Backfill or rebuild the Pages issues: python -m pipeline.newsletter --github-all
"""

import re
import sys
from datetime import date
from pathlib import Path

from . import config

REPO_URL = "https://github.com/benjaminchoe123/threat-intel-pipeline"
SITE_URL = "https://benjaminchoe123.github.io/threat-intel-pipeline"
DOCS_DIR = config.ROOT / "docs"
WEEK_RE = re.compile(r"^(\d{4})-W(\d{2})$")

ISSUE_INTRO = """*Signal & Noise separates the threats that matter from the feed noise — a weekly,
plain-English threat report for small orgs and IT generalists, generated by an
[open-source automated pipeline]({repo}) and gated by a verification check and a human
before anything ships.* · [All issues]({site}/newsletter/) · [RSS]({site}/feed.xml)

"""

ISSUE_FOOTER = """

---

*How this issue was made: an automated pipeline ingests public threat feeds (CISA KEV,
abuse.ch, and others), Claude enriches each item into a structured analyst note, and a
weekly report is drafted from those notes. Every CVE and claim is checked against the
source notes before publication, and a human can stop any issue. The pipeline, its tests
and its audit trail are public: {repo}.*

**Get each issue as it lands:** add the [RSS feed]({site}/feed.xml) to any feed reader.
Free, weekly, no account.
"""

HEADER = """*Signal & Noise separates the threats that matter from the feed noise — a weekly,
plain-English threat report for small orgs and IT generalists, generated by an
[open-source automated pipeline]({repo}) and reviewed by a human before anything ships.*

---

"""

FOOTER = """

---

*How this issue was made: an automated pipeline ingests public threat feeds (CISA KEV,
abuse.ch, and others), Claude enriches each item into a structured analyst note, and a
weekly report is drafted from those notes. A human reviews and approves every issue before
it is published — nothing here is posted unread. The pipeline, its tests, and this week's
full report are public: {repo}.*

**Subscribe for one issue a week, free — if this was useful, that's the whole pitch.**
"""


def _published_report(vault_dir, wid):
    """Path to the published report — drafts are refused, so an issue can never
    cite something that has not passed the publish gate."""
    published = Path(vault_dir) / "reports" / f"{wid}.md"
    if not published.exists():
        draft = Path(vault_dir) / "reports" / "drafts" / f"{wid}-DRAFT.md"
        if draft.exists():
            raise FileNotFoundError(
                f"{wid} is still a draft — review it and run "
                f"`python -m pipeline.publish {wid}` first"
            )
        raise FileNotFoundError(f"no published report for {wid} at {published}")
    return published


def published_weeks(vault_dir):
    """Every published week, oldest first. Issue numbers are positions in this."""
    reports = Path(vault_dir) / "reports"
    if not reports.is_dir():
        return []
    return sorted(p.stem for p in reports.glob("*.md") if WEEK_RE.match(p.stem))


def _week_sunday(wid):
    m = WEEK_RE.match(wid)
    if not m:
        raise ValueError(f"not a week id: {wid!r}")
    return date.fromisocalendar(int(m.group(1)), int(m.group(2)), 7)


def _strip_h1(text):
    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "\n".join(lines).strip("\n")


def build_issue_page(vault_dir, wid, docs_dir=None):
    """Write the GitHub Pages issue for `wid` to docs/_posts/. Returns its path.

    Everything in the page derives from the report and its week, nothing from
    the clock, so a rebuild of an unchanged issue is byte-identical — the same
    rule as the STIX and Navigator exports. Overwriting is therefore safe and
    is what --github-all relies on.

    The body sits inside {% raw %}: Pages runs Liquid over every page, and one
    `{{` in a report would fail the build for the whole site. A raw tag inside
    the report would end the escape early, so those are defused first.
    """
    docs_dir = Path(docs_dir) if docs_dir else DOCS_DIR
    published = _published_report(vault_dir, wid)
    weeks = published_weeks(vault_dir)
    number = weeks.index(wid) + 1
    sunday = _week_sunday(wid)

    body = _strip_h1(published.read_text(encoding="utf-8"))
    body = re.sub(r"\{%-?\s*(end)?raw\s*-?%\}", lambda m: m.group(0).replace("%", "&#37;"), body)
    page = (
        "---\n"
        "layout: default\n"
        f'title: "Signal & Noise #{number} — {wid}"\n'
        f"date: {sunday.isoformat()}\n"
        f"week: {wid}\n"
        "---\n\n"
        f"# Signal & Noise #{number} — {wid}\n\n"
        f"*Week ending {sunday:%B} {sunday.day}, {sunday.year}*\n\n"
        "{% raw %}\n"
        + ISSUE_INTRO.format(repo=REPO_URL, site=SITE_URL)
        + body
        + ISSUE_FOOTER.format(repo=REPO_URL, site=SITE_URL)
        + "{% endraw %}\n"
    )
    out = docs_dir / "_posts" / f"{sunday.isoformat()}-signal-noise-{wid}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8", newline="\n")
    return out


def build_newsletter(vault_dir, wid):
    """Wrap the published report for `wid` in newsletter boilerplate.

    Reads vault/reports/<wid>.md (published only — drafts are refused so the
    newsletter can never cite something that hasn't passed human review) and
    writes vault/reports/newsletter/<wid>-substack.md.
    """
    vault_dir = Path(vault_dir)
    published = _published_report(vault_dir, wid)

    out_dir = vault_dir / "reports" / "newsletter"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{wid}-substack.md"
    if out.exists():
        raise FileExistsError(f"{out} already exists — refusing to overwrite")

    body = published.read_text(encoding="utf-8")
    out.write_text(
        HEADER.format(repo=REPO_URL) + body + FOOTER.format(repo=REPO_URL),
        encoding="utf-8",
    )
    return out


def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    if argv == ["--github-all"]:
        for wid in published_weeks(config.VAULT_DIR):
            print(f"issue page: {build_issue_page(config.VAULT_DIR, wid)}")
        return 0
    if len(argv) != 1:
        print("usage: python -m pipeline.newsletter <YYYY-Wnn>  |  "
              "python -m pipeline.newsletter --github-all")
        return 2
    try:
        out = build_newsletter(config.VAULT_DIR, argv[0])
    except (FileNotFoundError, FileExistsError) as exc:
        print(exc)
        return 1
    print(f"Substack copy ready to paste: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
